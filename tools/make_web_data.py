#!/usr/bin/env python3
"""Writes docs/builder/release-data.js for the web builder (docs/index.html) from firmware/:
device.json, the tweaks in firmware/patch.py's MODS (in that order) and its EXPECT_MAIN_OS.

    python3 tools/make_web_data.py            # write
    python3 tools/make_web_data.py --check    # fail if the committed file is out of date
"""
import ast
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TW = ROOT / "firmware" / "tweaks" / "model-cycles_OS1.13"
OUT = ROOT / "docs" / "builder" / "release-data.js"


def render():
    patch = (ROOT / "firmware" / "patch.py").read_text(encoding="utf-8")
    mods = ast.literal_eval(re.search(r"^MODS = (\[.*?\])$", patch, re.M | re.S).group(1))
    expect = re.search(r'^EXPECT_MAIN_OS = "([0-9a-f]{64})"', patch, re.M).group(1)
    by_id = {}
    for p in sorted(TW.glob("*.json")):
        if p.name != "device.json":
            t = json.loads(p.read_text(encoding="utf-8"))
            by_id[t["id"]] = t
    missing = [m for m in mods if m not in by_id]
    if missing:
        sys.exit(f"!! tweaks missing from firmware/: {missing}")
    data = {"device": json.loads((TW / "device.json").read_text(encoding="utf-8")),
            "mods": [by_id[m] for m in mods], "expectMainOs": expect,
            "output": "modded-cycles-techno-edition.syx"}
    return ("/* Generated by tools/make_web_data.py from firmware/ (patch.py, tweaks). Do not edit by hand. */\n"
            "window.MCTE_RELEASE = " + json.dumps(data, separators=(",", ":")) + ";\n")


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.exit(f"!! {OUT.relative_to(ROOT)} is out of date: run python3 tools/make_web_data.py")
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text) // 1024} KB)")


if __name__ == "__main__":
    main()
